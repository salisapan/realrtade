#!/usr/bin/env node
// Marker.js must match src/marker.js (Apps Script ships Marker.js).
const fs = require('fs');
const path = require('path');

const addon = path.join(__dirname, '..');
const src = fs.readFileSync(path.join(addon, 'src', 'marker.js'), 'utf8').replace(/\s+$/, '') + '\n';
const shipped = fs.readFileSync(path.join(addon, 'Marker.js'), 'utf8');
const prefix = '// Generated by glance-gmail-addon/scripts/build-bundle.js from src/marker.js\n';
const expected = prefix + src;
if (shipped !== expected) {
  console.error('Marker.js drift: re-run node glance-gmail-addon/scripts/build-bundle.js and commit Marker.js');
  process.exit(1);
}
console.log('Marker.js matches src/marker.js');
