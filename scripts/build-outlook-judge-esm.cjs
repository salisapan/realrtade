#!/usr/bin/env node
// Bundle flow-trial-extension/core for Deno/Node judge (Outlook Graph marker).
// Same sources as glance-gmail-addon CoreBundle classifier chain — no forked logic.
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');

const repo = path.join(__dirname, '..');
const core = path.join(repo, 'flow-trial-extension', 'core');
const outDir = path.join(repo, 'supabase', 'functions', 'outlook-graph-glance');
const outMjs = path.join(outDir, 'judge-bundle.mjs');
const manifestPath = path.join(outDir, 'judge-bundle.manifest.json');

const FILES = [
  'domains.js',
  'extract.js',
  'judgment.js',
  'google-closes.js',
  'close-families.js',
  'fact-reply.js',
  'file-attach.js',
  'intent.js',
  'actions.js',
  'resolution.js',
  'incoming-judge.js'
];

function stripCjsExport(src) {
  return src
    .replace(/\nif \(typeof module !== 'undefined'\) module\.exports\s*=\s*(\{[\s\S]*?\}|[^;]+);?\s*\nelse if \(typeof globalThis[^\n]*\n?/g, '\n')
    .replace(/\nif \(typeof module !== 'undefined'\) module\.exports\s*=\s*(\{[\s\S]*?\}|[^;]+);?\s*$/gm, '\n')
    .replace(/\nelse if \(typeof globalThis[^\n]*\n?/g, '\n');
}

const parts = [
  '// Generated by scripts/build-outlook-judge-esm.cjs — do not edit.',
  '// Sources: flow-trial-extension/core/*.js (see judge-bundle.manifest.json).',
  ''
];
const manifest = { generatedAt: new Date().toISOString(), files: [] };

for (const name of FILES) {
  const file = path.join(core, name);
  const raw = fs.readFileSync(file, 'utf8');
  const sha = crypto.createHash('sha256').update(raw).digest('hex');
  manifest.files.push({ file: `flow-trial-extension/core/${name}`, sha256: sha });
  parts.push(`// ----- ${name} -----`);
  parts.push(stripCjsExport(raw.replace(/\s+$/, '')));
  parts.push('');
}

parts.push(`
export function judgeIncoming(input) {
  if (typeof FlowIncomingJudge === 'undefined' || !FlowIncomingJudge.judge) {
    return { show: false, reason: 'no-judge', intent: null };
  }
  const row = Object.assign({ surface: 'outlook', inbound: true }, input || {});
  return FlowIncomingJudge.judge(row, {});
}

export function shouldOfferDoIt(out) {
  return Boolean(out && out.show === true && out.process && out.process.steps && out.process.steps.length);
}
`);

fs.mkdirSync(outDir, { recursive: true });
fs.writeFileSync(outMjs, parts.join('\n'));
fs.writeFileSync(manifestPath, JSON.stringify(manifest, null, 2) + '\n');
console.log('wrote', path.relative(repo, outMjs), '(' + FILES.length + ' sources)');
