#!/usr/bin/env node
// Builds core/local-lm-audit.js: a small, fixed, balanced set of sentences the extension uses to test an on-device
// language model on the device itself before it is allowed to propose anything (core/local-lm.js selfTest).
//   node scripts/intent/build-lm-audit.cjs
// Sentences come from the held-out teacher evaluation sets (synthetic, written by the build-time teacher model, public).
// Selection is deterministic: every k-th row of each class, per language. Never edit the output by hand.
const fs = require('fs');
const path = require('path');
const ROOT = path.join(__dirname, '..', '..', 'flow-trial-extension');
const fx = (f) => JSON.parse(fs.readFileSync(path.join(ROOT, 'test', 'fixtures', f), 'utf8'));
const rows = fx('intent-teacher-eval-2.json').concat(fx('intent-teacher-eval.json'));
const PER = { ASK: 14, PROMISE: 14, INFORM: 14, ACK: 10 };
const out = [];
for (const lang of ['en', 'he']) {
  for (const act of Object.keys(PER)) {
    const pool = rows.filter((r) => (r.lang === 'he' ? 'he' : 'en') === lang && r.act === act && r.t.split(/\s+/).length >= 5 && r.t.split(/\s+/).length <= 30);
    const step = Math.max(1, Math.floor(pool.length / PER[act]));
    let taken = 0;
    for (let i = 0; i < pool.length && taken < PER[act]; i += step) { out.push({ t: pool[i].t, act, lang }); taken++; }
  }
}
const body = '// GENERATED by scripts/intent/build-lm-audit.cjs. Do not edit by hand.\n' +
  '// The fixed sentences an on-device language model must pass on THIS device before core/local-lm.js lets it propose anything.\n' +
  'const FlowLocalLMAudit = ' + JSON.stringify(out, null, 1) + ';\n\nif (typeof module !== \'undefined\') module.exports = { FlowLocalLMAudit };\n';
fs.writeFileSync(path.join(ROOT, 'core', 'local-lm-audit.js'), body);
const c = {}; out.forEach((r) => { const k = r.lang + ':' + r.act; c[k] = (c[k] || 0) + 1; });
console.log('wrote core/local-lm-audit.js', out.length, 'sentences', JSON.stringify(c));
